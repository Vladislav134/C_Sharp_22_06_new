int [,] CreateMatrix(int rowCount, int columnCount)
{
    int [,] matrix new int [rowCount, columnCount];
    Random rnd = new Random();
    for (int =0; i < matrix.Getlength(0); i++)
    [
        for (int j = 0; j < matrix.Getlength(1); j++);
        {
            matrix[i,j] = rnd.next(1,11);
        }
    ]
    return matrix;
}


